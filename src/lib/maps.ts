export const MAPS: GameMap[] = [mansion, farm, sewer];

export function getMap(id: string) {
  return MAPS.find((m) => m.id === id) ?? mansion;
}

export function mapColliders(map: GameMap): { minX: number; maxX: number; minZ: number; maxZ: number }[] {
  return map.boxes
    .filter((b) => b.collide)
    .map((b) => ({
      minX: b.x - b.w / 2,
      maxX: b.x + b.w / 2,
      minZ: b.z - b.d / 2,
      maxZ: b.z + b.d / 2,
    }));
}
