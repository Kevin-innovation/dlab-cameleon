import type { BoxDef, GameMap, Pattern } from "./types";

function B(
  x: number,
  z: number,
  w: number,
  d: number,
  color: string,
  extra: Partial<BoxDef> & { h?: number; y?: number } = {},
): BoxDef {
  const h = extra.h ?? 0.9;
  const y = extra.y ?? 0;
  return {
    x: x + w / 2,
    y: y + h / 2,
    z: z + d / 2,
    w,
    h,
    d,
    color,
    pattern: extra.pattern,
    colors: extra.colors,
    collide: extra.collide,
  };
}

